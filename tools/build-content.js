#!/usr/bin/env node
/* Builds the content pack every platform reads.
     content/src/*.json   the source: edit these
     content/bundle.json  all banks in one file, read by the native apps
     content/bundle.js    the same data for the web app
     content/manifest.json  version, schema and checksum; apps check this to find a new pack
   Pack text may only use the small markup listed in docs/CONTENT.md, so every platform can draw it. */
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const ROOT=path.join(__dirname,'..'),SRC=path.join(ROOT,'content','src'),OUT=path.join(ROOT,'content');
const FILES=['meta','language','people','brain','vocabulary','words','discovery','expert','interests','stories'];
const c={};FILES.forEach(f=>c[f]=JSON.parse(fs.readFileSync(path.join(SRC,f+'.json'),'utf8')));

// Only this markup is allowed in pack text.
const OK=/^(<\/?b>|<br>|<div class="(bigletter|wx big|passage|wsent)">|<\/div>|<span class="blank">|<\/span>)$/;
const bad=[];
const walk=(v,where)=>{
  if(typeof v==='string'){for(const m of v.match(/<[^>]*>/g)||[])if(!OK.test(m))bad.push(`${where}: ${m}`)}
  else if(Array.isArray(v))v.forEach((x,i)=>walk(x,`${where}/${i}`));
  else if(v&&typeof v==='object')Object.entries(v).forEach(([k,x])=>walk(x,`${where}/${k}`));
};
['language','people','brain','vocabulary','discovery','expert'].forEach(f=>walk(c[f],f));
if(bad.length){console.error('Markup that other platforms cannot draw:\n- '+bad.slice(0,20).join('\n- '));process.exit(1)}

const json=JSON.stringify(c),sha256=crypto.createHash('sha256').update(json).digest('hex');
fs.writeFileSync(path.join(OUT,'bundle.json'),json);
fs.writeFileSync(path.join(OUT,'bundle.js'),`/* Generated by tools/build-content.js from content/src. Do not edit. */
const CONTENT=${json};
const BANK=CONTENT.meta;
const {NOUNS,ADJS,VERBS,ADVS,LY_TRAPS,TRICKY_N,CONCRETE,NO_CLOUD,PROPER,WORDTAG,TAGNAME,TAGTEST,SENTS,ADV_SENTS,PUNCT,PROOF,FACTS}=CONTENT.words;
const LANG_SKILLS=CONTENT.language.skills,LANG_ITEMS=CONTENT.language.items;
const SOCIAL=CONTENT.people.situations;
const EF_SKILLS=CONTENT.brain.skills,EF_ITEMS=CONTENT.brain.items;
const VOCAB=CONTENT.vocabulary.words;
const DISCOVERIES=CONTENT.discovery,EXPERT=CONTENT.expert;
const {INTERESTS,THEMES}=CONTENT.interests;
const {STORIES,STORY_TYPES}=CONTENT.stories;
`);
fs.writeFileSync(path.join(OUT,'manifest.json'),JSON.stringify({schema:c.meta.schema,version:c.meta.version,date:c.meta.log[c.meta.log.length-1].d,bundle:'bundle.json',bytes:Buffer.byteLength(json),sha256},null,2)+'\n');
console.log(`Content pack version ${c.meta.version} (schema ${c.meta.schema}): ${Buffer.byteLength(json)} bytes`);
